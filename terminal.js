// ── Helpers ───────────────────────────────────────────

function line(text = '', cls = '') {
  const el = document.createElement('span');
  el.className = 'line' + (cls ? ' line-' + cls : '');
  el.innerHTML = text;
  output.appendChild(el);
  scrollBottom();
  return el;
}

function gap() { line('', ''); }
function scrollBottom() { window.scrollTo(0, document.body.scrollHeight); }
function echoCmd(cmd) { line(`runox@amoeboid:~$ ${cmd}`, 'echo'); }
function delay(ms) { return new Promise(r => setTimeout(r, ms)); }

function printLines(lines, interval = 20) {
  return new Promise(resolve => {
    let i = 0;
    function next() {
      if (i >= lines.length) { resolve(); return; }
      const entry = lines[i];
      const [text, cls] = Array.isArray(entry) ? entry : [entry, ''];
      setTimeout(() => { line(text, cls); i++; next(); }, interval);
    }
    next();
  });
}

function typewriter(text, cls = '', speed = 28) {
  return new Promise(resolve => {
    const el = line('', cls);
    let i = 0;
    function tick() {
      if (i > text.length) { resolve(); return; }
      el.textContent = text.slice(0, i++);
      setTimeout(tick, speed);
    }
    tick();
  });
}

